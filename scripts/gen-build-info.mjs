#!/usr/bin/env node
/*
 * Regenerates src/build-info.js with the current git SHA + build timestamp.
 *
 * Runs automatically as the npm "prebuild" step (so every `npm run build` stamps the frontend
 * bundles) and from deploy-and-grade.sh right before `forge deploy` (so the backend bundle is
 * stamped even if the build step ever changes). A committed placeholder version of
 * src/build-info.js exists so the Forge backend bundle always resolves the import even on a
 * fresh checkout that never ran this script.
 *
 * The stamp is surfaced two ways for deploy-staleness detection (the it26 lesson — an install
 * can serve a frozen frontend while resolvers update):
 *   - testhook `what=version` → { build: BUILD_INFO }   (backend bundle truth)
 *   - `data-sv-build` attribute on the realm/steward console root containers (frontend truth)
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

let gitSha = "unknown";
try {
  gitSha = execSync("git rev-parse --short HEAD", { cwd: root, stdio: ["ignore", "pipe", "ignore"] })
    .toString()
    .trim();
} catch (_) {
  // Not a git checkout (or git unavailable) — keep the "unknown" sentinel; never fail the build.
}

const builtAt = new Date().toISOString();

const content = `/*
 * GENERATED by scripts/gen-build-info.mjs — do NOT hand-edit.
 * A placeholder is COMMITTED so the Forge backend bundle always resolves this import;
 * the generator overwrites it locally on every npm build / deploy (commit churn expected).
 */
export const BUILD_INFO = { gitSha: "${gitSha}", builtAt: "${builtAt}" };
`;

writeFileSync(join(root, "src", "build-info.js"), content);
console.log(`[gen-build-info] stamped ${gitSha} @ ${builtAt}`);
